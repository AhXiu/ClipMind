object AiModelCatalog {
    const val UPDATED_AT = "2026-09-12"

    fun models(provider: String): List<String> = when (provider) {
        "ark" -> emptyList() // Ark uses deployment IDs belonging to the user's account.
        "kimi" -> listOf("kimi-k3", "kimi-k2.6", "kimi-k2.7-code", "kimi-k2.7-code-highspeed")
        "glm" -> listOf("glm-5.3", "glm-5.3-flash", "glm-5.2")
        "openai" -> listOf("gpt-4.1-mini", "gpt-5-mini", "gpt-6-astra")
        "openrouter" -> openRouterModels
        else -> emptyList()
    }

    fun options(provider: String, savedModel: String): List<String> =
        (models(provider) + listOf(savedModel).filter(String::isNotBlank)).distinct()

    fun search(models: List<String>, query: String): List<String> =
        models.filter { it.contains(query.trim(), ignoreCase = true) }

    fun common(provider: String, current: String, recent: List<String>): List<String> {
        val catalogue = models(provider)
        val common = if (provider == "openrouter") listOf(
            "openai/gpt-4.1-mini", "anthropic/claude-sonnet-4.6", "google/gemini-2.5-flash",
            "moonshotai/kimi-k3", "z-ai/glm-5.3", "deepseek/deepseek-v3.2", "qwen/qwen3.6-plus",
        ).filter { it in catalogue } else catalogue.take(6)
        return (listOf(current) + recent.take(5) + common).filter { AiDefaults.validModel(it) }.distinct()
    }

